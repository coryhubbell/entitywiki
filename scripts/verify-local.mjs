#!/usr/bin/env node
/** Exercises an explicitly local staging database. Never calls the live wiki. */
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const origin = new URL(process.argv[2] ?? 'http://127.0.0.1:8876');
if (!['http:', 'https:'].includes(origin.protocol) || !['127.0.0.1', 'localhost', '[::1]'].includes(origin.hostname) || origin.username || origin.password || origin.pathname !== '/' || origin.search || origin.hash) throw new Error('Only a loopback staging origin is allowed.');
const vars = await readFile(new URL('../.dev.vars', import.meta.url), 'utf8');
const key = /^OPERATOR_LOCAL_KEY=(.+)$/m.exec(vars)?.[1]?.trim();
if (!key || key.length < 32) throw new Error('Configure an ignored .dev.vars file with a local staging key.');
const get = (path, headers = {}) => fetch(new URL(path, origin), { headers, redirect: 'manual' });
const post = (path, body, cookie) => fetch(new URL(path, origin), { method: 'POST', redirect: 'manual', headers: { 'Content-Type': 'application/json', Origin: origin.origin, Cookie: cookie }, body: JSON.stringify(body) });
assert.equal((await get('/api/health')).status, 200);
assert.equal((await get('/api/records/maxplaces-marketing')).status, 403);
assert.equal((await post('/api/import', { mode: 'restore_pilot' }, '')).status, 403);
const login = await fetch(new URL('/admin/auth', origin), { method: 'POST', redirect: 'manual', headers: { 'Content-Type': 'application/x-www-form-urlencoded', Origin: origin.origin }, body: new URLSearchParams({ key }) });
assert.equal(login.status, 303);
const cookie = login.headers.get('set-cookie')?.split(';')[0];
assert.ok(cookie, 'Local session cookie is required.');
const before = await get('/api/public/records/maxplaces-marketing');
const restored = await post('/api/import', { mode: 'restore_pilot' }, cookie);
assert.equal(restored.status, 200);
const { recordId } = await restored.json();
assert.equal(recordId, 'rev_1457a83ebaa25934ec7241c23ee2b226');
const adminResponse = await get('/api/records/maxplaces-marketing', { Cookie: cookie });
assert.equal(adminResponse.status, 200);
const admin = await adminResponse.json();
assert.equal(admin.record.revision, 2);
assert.equal(admin.record.coverage.acceptedOntologyMappings, 6);
assert.equal(admin.record.coverage.verifiedGoogleLocations, 2);
assert.equal(admin.record.coverage.unresolvedConflicts, 1);
if (before.status === 404) assert.equal((await get('/api/public/records/maxplaces-marketing')).status, 404, 'Restoration must not release a record.');
const released = await post('/api/releases', { recordId, expectedPreviousReleaseId: admin.webRelease?.id ?? null, reason: 'Local staging migration validation; no live routing change.' }, cookie);
assert.equal(released.status, 200);
const publicResponse = await get('/api/public/records/maxplaces-marketing');
assert.equal(publicResponse.status, 200);
const dossier = await publicResponse.json();
assert.equal(dossier.record.id, recordId);
assert.equal(dossier.record.entityId, 'ew_a3d1e72a720be01b2e5834cb');
assert.equal('actor' in dossier.webRelease, false);
assert.equal('reason' in dossier.webRelease, false);
const artifactPath = `/api/releases/${dossier.webRelease.id}/artifact`;
assert.equal((await get(artifactPath)).status, 403, 'Release exports require operator authentication.');
const artifactResponse = await get(artifactPath, { Cookie: cookie });
assert.equal(artifactResponse.status, 200);
assert.equal(artifactResponse.headers.get('cache-control'), 'no-store');
const artifact = await artifactResponse.json();
assert.equal(artifact.format, 'entitywiki.public-release/1');
assert.equal(createHash('sha256').update(artifact.projectionCanonical).digest('hex'), dossier.webRelease.digest);
assert.deepEqual(JSON.parse(artifact.projectionCanonical), { record: dossier.record, jsonld: dossier.jsonld, graph: dossier.graph });
assert.equal('actor' in artifact.release, false);
assert.equal('reason' in artifact.release, false);
const schemaResponse = await get('/api/public/records/maxplaces-marketing/schema.jsonld');
const schema = await schemaResponse.json();
assert.deepEqual(schema, dossier.jsonld);
assert.ok(JSON.stringify(schema).includes('https://entitywiki.org/id/ew_a3d1e72a720be01b2e5834cb'));
assert.ok(!JSON.stringify(schema).includes(origin.origin));
const identity = await get('/id/ew_a3d1e72a720be01b2e5834cb');
assert.equal(identity.status, 303);
assert.equal(identity.headers.get('location'), '/MAXPlaces_Marketing');
assert.equal((await get(`/api/public/revisions/${recordId}`)).status, 200);
const page = await get('/MAXPlaces_Marketing');
assert.equal(page.status, 200);
assert.equal(page.headers.get('x-robots-tag'), 'noindex, nofollow');
const html = await page.text();
assert.ok(html.includes('https://entitywiki.org/MAXPlaces_Marketing'));
assert.ok(html.includes('application/ld+json'));
assert.equal((await post('/publications/publish', {}, cookie)).status, 404);
assert.equal((await post('/api/publications/publish', { planId: 'intentionally_not_a_live_plan' }, cookie)).status, 409);
console.log(JSON.stringify({ ok: true, origin: origin.origin, recordId, preservedRevision: 2, stableEntityIds: dossier.record.entities.length, ontologyMappings: 6, googlePlaceMatches: 2, unresolvedPostalConflicts: 1, releaseArtifact: 'captured_and_verified', anonymousArtifactExport: 'denied', liveWikiWriting: 'disabled', anonymousAdminAccess: 'denied', stagingNoindex: true }));
